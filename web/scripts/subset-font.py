"""재생성: uv run --no-project --with fonttools --with brotli python web/scripts/subset-font.py

원본 Pretendard의 모든 문자를 보존하면서 영문·한글 UI·나머지를 나누어 전송한다.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools import subset

root = Path(__file__).resolve().parents[1]
original = root / "public/fonts/PretendardVariable.woff2"
codes = set(TTFont(original).getBestCmap())
latin = {c for c in codes if c < 0x300 or 0x2000 <= c <= 0x2BFF or c == 0xFEFF}
text = "".join(p.read_text() for p in (root / "src").rglob("*") if p.suffix in {".ts", ".tsx"})
text += "".join(p.read_text() for p in (root.parent / "scenarios").glob("*.json"))
common = {ord(c) for c in text} & codes - latin

def ranges(values):
    result = []
    for c in sorted(values):
        if result and c == result[-1][1] + 1:
            result[-1][1] = c
        else:
            result.append([c, c])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in result)

rules = []
for name, chars in [("latin", latin), ("ui", common), ("extended", codes - latin - common)]:
    font = TTFont(original, recalcTimestamp=False)
    options = subset.Options()
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=chars)
    sub.subset(font)
    path = root / f"public/fonts/pretendard-{name}.woff2"
    font.save(path)
    rules.append(f'@font-face{{font-family:"Pretendard Variable";src:url("/fonts/{path.name}") format("woff2");font-weight:100 900;font-style:normal;font-display:swap;unicode-range:{ranges(chars)};}}')
    print(name, len(chars), path.stat().st_size)
(root / "src/fontSubsets.css").write_text("/* Generated by scripts/subset-font.py; preserves the complete original character map. */\n" + "\n".join(rules) + "\n")
